HEDGE_RE = re.compile(r"도움|좋지만|돕")


def norm(s: str) -> str:
    return re.sub(r"[\s·()（）]", "", s)


if __name__ == "__main__":
    total = 0
    by_norm = defaultdict(set)
    by_type = Counter()
    for rel, types in P.items():
        n = sum(len(v) for v in types.values())
        total += n
        for t, phrases in types.items():
            by_type[t] += len(phrases)
            for ph in phrases:
                by_norm[norm(ph)].add(rel)
        print(f"{rel}: {n}개 {dict((t, len(v)) for t, v in types.items())}")
    print(f"\n합계(중복 포함) {total}개, 공백·가운뎃점·괄호 제거 기준 서로 다른 문구 {len(by_norm)}개")
    print("유형별(중복 포함):", dict(by_type))
    multi = sorted(((k, len(v)) for k, v in by_norm.items() if len(v) > 1), key=lambda x: -x[1])
    print("여러 보도자료에 반복:", multi)
    print("헷지형:", [(ph, rel) for rel, types in P.items() for v in types.values() for ph in v if HEDGE_RE.search(ph)])
